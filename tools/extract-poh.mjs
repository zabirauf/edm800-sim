// Extracts the 177B POH cruise table (research Appendix A) into src/sim/data/poh-cruise.js.
import { readFileSync, writeFileSync } from 'node:fs';
const md = readFileSync(new URL('../docs/research/o360-cardinal-data.md', import.meta.url), 'utf8');
const lines = md.split('\n');
const rows = [];
let alt = null;
for (const line of lines) {
  const h = /^\*\*(\d+) ft pressure altitude\*\*/.exec(line);
  if (h) { alt = Number(h[1]); continue; }
  if (/^## Appendix B/.test(line)) break;
  if (alt == null || !/^\| \d{4} \|/.test(line)) continue;
  const c = line.split('|').slice(1, -1).map((x) => x.trim().replace('*', ''));
  const num = (x) => (x === '—' || x === '' ? null : Number(x));
  const [rpm, mp] = [num(c[0]), num(c[1])];
  const isaC = 15 - 2 * (alt / 1000);
  [[-20, 2], [0, 5], [20, 8]].forEach(([dev, k]) => {
    const pct = num(c[k]);
    if (pct == null) return;
    rows.push({ alt, rpm, mp, isaDev: dev, oatC: isaC + dev, pct, ktas: num(c[k + 1]), gph: num(c[k + 2]) });
  });
}
const out = `// 177B POH cruise performance (Fig 5-7), recommended lean, 2500 lb, cowl flaps closed. [S2] via research Appendix A.
// Generated by tools/extract-poh.mjs — do not edit by hand.
export const POH_CRUISE = ${JSON.stringify(rows)};
`;
writeFileSync(new URL('../src/sim/data/poh-cruise.js', import.meta.url), out);
const byAlt = {};
for (const r of rows) byAlt[r.alt] = (byAlt[r.alt] || 0) + 1;
console.log('cells', rows.length, byAlt, 'ISA cells', rows.filter((r) => r.isaDev === 0).length);
